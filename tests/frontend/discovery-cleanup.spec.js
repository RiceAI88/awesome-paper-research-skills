import {test,expect} from './fixtures.js';
for (const width of [1280,390,320]) test(`filter panel and honest counts at ${width}px`,async({page})=>{
 await page.setViewportSize({width,height:900});
 const filterRequests=[];
 page.on('request',r=>{if(/\/assets\/FilterControls-.*\.js$/.test(r.url()))filterRequests.push(r.url());});
 await page.goto('./#discipline=science');
 expect(filterRequests).toHaveLength(0);
 await expect(page.locator('[data-discipline="science"]')).toHaveText('理学');
 await expect(page.locator('.discipline-selector-heading')).toContainText(/当前结果 \d+：专业适用 \d+ ＋ 通用 \d+/);
 await expect(page.locator('#agentFilter')).not.toBeVisible();
 const trigger=page.getByRole('button',{name:/^筛选/});
 await trigger.click();
 const panel=page.getByRole('dialog',{name:'筛选条件'});
 await expect(panel).toBeVisible();
 await expect(panel.locator('#agentFilter')).toBeVisible();
 expect(filterRequests).toHaveLength(1);
 await panel.locator('#agentFilter').click();
 await page.locator('.ant-select-item-option[title="Claude Code"]').click();
 await expect(page).toHaveURL(/agent=claude-code/);
 await panel.locator('#sortSelect').click();
 await page.locator('.ant-select-item-option[title="排序：最新收录"]').click();
 await expect(trigger).toContainText('2');
 await expect(panel.getByRole('button',{name:'完成',exact:true})).toHaveCount(0);
 await panel.getByRole('button',{name:'关闭',exact:true}).click();
 await expect(panel).not.toBeVisible();
 await trigger.click();
 await page.keyboard.press('Escape');
 await expect(trigger).toBeFocused();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
